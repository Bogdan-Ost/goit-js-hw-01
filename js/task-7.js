// Умова: Маєте масив температур у градусах Цельсія. Створіть новий масив, де всі температури будуть переведені у Фаренгейти за формулою: F = C * 1.8 + 32.
// • Вхідний масив: [0, 10, 20, 30]
// • Очікуваний результат: [32, 50, 68, 86]

const celcie = [0, 10, 20, 30];

const faringate = celcie.map(item => {
  return item * 1.8 + 32;
});

console.log(faringate);

