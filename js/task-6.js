// • Завдання 6: Фільтрація імен
// 	• Умова: Є масив імен let users = ["Олена", "Ігор", "Анна", "Олег", "Ольга"]. Переберіть масив і виведіть у консоль лише ті імена, які починаються на літеру "О".
// • Завдання 7: Пошук максимального числа
// 	• Умова: Створіть масив довільних чисел. За допомогою циклу for...of знайдіть найбільше число в цьому масиві та виведіть його. (Підказка: не використовуйте Math.max(), зробіть це вручну через порівняння).
// • Завдання 8: Підрахунок літер
// 	• Умова: Є рядок let sentence = "JavaScript — це круто". Цикл for...of вміє перебирати рядок посимвольно. Порахуйте, скільки разів у цьому рядку зустрічається літера "а".

